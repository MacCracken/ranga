#!/usr/bin/env python3
"""Turn the Rust 1.0.1 oracle output into the golden digests tests/ check.

Usage: make_golden.py build/oracle/rust.out > scripts/oracle/golden_rust.cyr

For every group, this records the number of lines and an FNV-1a 64 digest over the
exact line text, each line including its newline. tests/oracle_golden.tcyr runs the
same group code (scripts/oracle/probe_core.cyr) in golden mode, computes the same
digests in-process, and compares. Groups accepted within a bound by an ADR
(compare.py's ACCEPTED) are not exact by design, so they are listed and skipped.
"""
import importlib.util
import os
import sys
from collections import OrderedDict

FNV_OFFSET = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3
MASK = (1 << 64) - 1


def accepted_groups():
    # Loading compare.py as a module would otherwise leave a __pycache__ in the tree.
    sys.dont_write_bytecode = True
    here = os.path.dirname(os.path.abspath(__file__))
    spec = importlib.util.spec_from_file_location("compare", os.path.join(here, "compare.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.ACCEPTED


def main(argv):
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    groups = OrderedDict()
    with open(argv[1], "rb") as f:
        for raw in f:
            line = raw.rstrip(b"\n")
            name = line.split(b"\t", 1)[0].decode()
            count, h = groups.get(name, (0, FNV_OFFSET))
            for b in line + b"\n":
                h = ((h ^ b) * FNV_PRIME) & MASK
            groups[name] = (count + 1, h)
    if not groups:
        print("no oracle output to digest", file=sys.stderr)
        return 2
    accepted = accepted_groups()
    out = sys.stdout
    out.write("# golden_rust.cyr -- GENERATED by scripts/oracle/make_golden.py from the Rust 1.0.1\n")
    out.write("# oracle output (scripts/oracle/run.sh). Do not edit by hand: regenerate it.\n")
    out.write("#\n")
    out.write("# Per group: line count and FNV-1a 64 over the exact line text. Checked by\n")
    out.write("# tests/oracle_golden.tcyr, which defines golden_expect().\n")
    for g in accepted:
        if g in groups:
            out.write(f"# skipped (accepted within a bound by an ADR, see compare.py): {g}\n")
    out.write("\nfn golden_check_all() {\n")
    for g, (count, h) in groups.items():
        if g in accepted:
            continue
        out.write(f'    golden_expect("{g}", {count}, 0x{h:016X});\n')
    out.write("    return 0;\n}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
